//! `series/<name>/view.sql`: a DuckDB view hiding schema evolution.
//!
//! Regenerated each flush; unions all epochs by name and coalesces keys that
//! were undeclared in some epoch against `extra`. Derived from the manifest,
//! so losing it in a crash is harmless.

use std::collections::BTreeSet;

use crate::config::KeyDef;
use crate::manifest::EpochSchema;
use crate::record::KeyType;

fn sql_str(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// Must match [`crate::flush::parquet::parquet_schema`].
fn duckdb_type(ty: KeyType) -> &'static str {
    match ty {
        KeyType::Bool => "BOOLEAN",
        KeyType::I64 => "BIGINT",
        KeyType::F64 => "DOUBLE",
        KeyType::Str => "VARCHAR",
    }
}

/// Always quoted: key names come from user config and may be SQL keywords.
fn sql_ident(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}

/// `CREATE VIEW` for one series. `history` is oldest first. A key missing
/// from any epoch is coalesced against `extra`, where its values landed then.
pub fn view_sql(series: &str, history: &[EpochSchema]) -> String {
    let mut all_keys: Vec<&KeyDef> = Vec::new();
    for epoch in history {
        for k in &epoch.keys {
            if !all_keys.iter().any(|seen| seen.name == k.name) {
                all_keys.push(k);
            }
        }
    }

    let mut sql = String::new();
    sql.push_str("-- Generated by orc; regenerated on every flush. Do not edit.\n");
    sql.push_str("-- Paths are relative to the data directory, and DuckDB resolves them\n");
    sql.push_str("-- against the process working directory -- not this file's location:\n");
    sql.push_str(&format!(
        "--   cd <data_dir> && duckdb -c \".read series/{series}/view.sql\"\n"
    ));

    if history.is_empty() {
        sql.push_str("-- No epochs recorded for this series yet.\n");
    } else {
        let epochs: Vec<String> = history.iter().map(|e| e.epoch.to_string()).collect();
        sql.push_str(&format!("-- Epochs unioned: {}\n", epochs.join(", ")));
    }

    sql.push_str(&format!(
        "CREATE OR REPLACE VIEW {} AS SELECT\n",
        sql_ident(series)
    ));
    sql.push_str("  ts,\n  id,\n");

    for k in &all_keys {
        let present_everywhere = history
            .iter()
            .all(|e| e.keys.iter().any(|ek| ek.name == k.name));
        let ident = sql_ident(&k.name);
        if present_everywhere {
            sql.push_str(&format!("  {ident},\n"));
        } else {
            // DuckDB won't coalesce typed vs VARCHAR, so cast `extra`; `try_cast`
            // so one unparseable producer value doesn't fail the whole query.
            let ty = duckdb_type(k.ty);
            sql.push_str(&format!(
                "  coalesce({ident}, try_cast(extra[{}] AS {ty})) AS {ident},\n",
                sql_str(&k.name)
            ));
        }
    }

    sql.push_str("  extra,\n  data\n");
    sql.push_str(&format!(
        "FROM read_parquet({}, hive_partitioning = 1, union_by_name = 1);\n",
        sql_str(&format!("series/{series}/**/*.parquet"))
    ));
    sql
}

/// Columns the generated view exposes, in order.
pub fn view_columns(history: &[EpochSchema]) -> Vec<String> {
    let mut seen = BTreeSet::new();
    let mut cols = vec!["ts".to_string(), "id".to_string()];
    for epoch in history {
        for k in &epoch.keys {
            if seen.insert(k.name.clone()) {
                cols.push(k.name.clone());
            }
        }
    }
    cols.push("extra".to_string());
    cols.push("data".to_string());
    cols
}

#[cfg(test)]
mod tests {
    use super::*;

    fn key(name: &str) -> KeyDef {
        typed_key(name, KeyType::Str)
    }

    fn typed_key(name: &str, ty: KeyType) -> KeyDef {
        KeyDef {
            name: name.to_string(),
            ty,
            nullable: true,
        }
    }

    fn epoch(n: u32, names: &[&str]) -> EpochSchema {
        EpochSchema {
            epoch: n,
            keys: names.iter().map(|n| key(n)).collect(),
        }
    }

    #[test]
    fn stable_key_needs_no_coalesce() {
        let h = [epoch(0, &["symbol"]), epoch(1, &["symbol"])];
        let sql = view_sql("trades", &h);
        assert!(sql.contains("  \"symbol\",\n"), "{sql}");
        assert!(!sql.contains("coalesce"), "{sql}");
    }

    #[test]
    fn promoted_key_is_coalesced_against_extra() {
        // `venue`: in `extra` at epoch 0, declared at epoch 1.
        let h = [epoch(0, &["symbol"]), epoch(1, &["symbol", "venue"])];
        let sql = view_sql("trades", &h);
        assert!(sql.contains("  \"symbol\",\n"), "stable key: {sql}");
        assert!(
            sql.contains("coalesce(\"venue\", try_cast(extra['venue'] AS VARCHAR)) AS \"venue\""),
            "promoted key: {sql}"
        );
    }

    /// Without the cast, a promoted `i64` key would compare as a string.
    #[test]
    fn a_promoted_key_keeps_the_type_its_config_declares() {
        for (ty, sql_type) in [
            (KeyType::I64, "BIGINT"),
            (KeyType::F64, "DOUBLE"),
            (KeyType::Bool, "BOOLEAN"),
            (KeyType::Str, "VARCHAR"),
        ] {
            let h = [
                EpochSchema {
                    epoch: 0,
                    keys: vec![],
                },
                EpochSchema {
                    epoch: 1,
                    keys: vec![typed_key("size", ty)],
                },
            ];
            let sql = view_sql("trades", &h);
            assert!(
                sql.contains(&format!(
                    "coalesce(\"size\", try_cast(extra['size'] AS {sql_type})) AS \"size\""
                )),
                "{ty:?} should cast to {sql_type}: {sql}"
            );
        }
    }

    #[test]
    fn demoted_key_is_also_coalesced() {
        // Declared at epoch 0, dropped at epoch 1.
        let h = [epoch(0, &["venue"]), epoch(1, &[])];
        let sql = view_sql("trades", &h);
        assert!(
            sql.contains("coalesce(\"venue\", try_cast(extra['venue'] AS VARCHAR))"),
            "{sql}"
        );
    }

    #[test]
    fn identifiers_and_literals_are_quoted() {
        // Keyword and quote in names; the coalesce path escapes the name both
        // as identifier and as literal.
        let h = [epoch(0, &["select"]), epoch(1, &["select", "it's"])];
        let sql = view_sql("odd\"name", &h);
        assert!(sql.contains("\"select\","), "keyword as ident: {sql}");
        assert!(
            sql.contains("coalesce(\"it's\", try_cast(extra['it''s'] AS VARCHAR)) AS \"it's\""),
            "quote escaped differently in ident vs literal: {sql}"
        );
        assert!(sql.contains("VIEW \"odd\"\"name\""), "escaped ident: {sql}");
    }

    #[test]
    fn empty_history_still_produces_valid_sql() {
        let sql = view_sql("fresh", &[]);
        assert!(sql.contains("CREATE OR REPLACE VIEW \"fresh\""), "{sql}");
        assert!(sql.contains("ts,"), "{sql}");
        assert!(sql.contains("read_parquet("), "{sql}");
    }

    #[test]
    fn columns_are_union_of_all_epochs_in_first_seen_order() {
        let h = [epoch(0, &["a"]), epoch(1, &["a", "b"]), epoch(2, &["b"])];
        assert_eq!(
            view_columns(&h),
            ["ts", "id", "a", "b", "extra", "data"]
                .map(String::from)
                .to_vec()
        );
    }
}
